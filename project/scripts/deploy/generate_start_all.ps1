# Generate start-all.ps1 from install_config.json
# Usage:
#   .\scripts\deploy\generate_start_all.ps1 -ProjectRoot D:\SYFAXTYX\project -ConfigPath D:\SYFAXTYX\config\install_config.json

param(
    [string]$ProjectRoot = "",
    [string]$ConfigPath = "",
    [string]$InstallRoot = "",
    [string]$OutputPath = ""
)

$ErrorActionPreference = "Stop"
. (Join-Path $PSScriptRoot "_deploy_common.ps1")

if (-not $ConfigPath) {
    if ($InstallRoot) { $ConfigPath = Join-Path $InstallRoot "config\install_config.json" }
    else { throw "ConfigPath or InstallRoot required" }
}
if (-not $ProjectRoot) {
    $cfg = Get-Content $ConfigPath -Raw -Encoding UTF8 | ConvertFrom-Json
    $ProjectRoot = $cfg.ProjectRoot
}
if (-not $OutputPath) {
    $OutputPath = Join-Path $ProjectRoot "start-all.ps1"
}

$cfg = Get-Content $ConfigPath -Raw -Encoding UTF8 | ConvertFrom-Json

$frontendPath = Join-Path $ProjectRoot "fronted"
$backendPath = Join-Path $ProjectRoot "backend"
$neo4jBin = Join-Path $cfg.Neo4jHome "bin"
$minioExe = $cfg.MinioExe
$minioData = $cfg.MinioDataDir
$redisStart = Join-Path $ProjectRoot "tools\redis\start_redis.ps1"
$mineruProfile = if ($cfg.MineruProfile) { $cfg.MineruProfile } else { "local" }

$content = @"
# Auto-generated by install_and_start.ps1 — do not edit paths manually
# Regenerate: scripts\deploy\generate_start_all.ps1 -ConfigPath config\install_config.json

`$FrontendPath = "$frontendPath"
`$BackendPath   = "$backendPath"
`$BackendEntry = "app.py"
`$ProjectRoot  = "$ProjectRoot"

`$Neo4jPath     = "$neo4jBin"
`$MinioExePath  = "$minioExe"
`$MinioDataDir  = "$minioData"
`$MinioConsolePort = "$($cfg.MinioConsolePort)"

`$MineruProfile = "$mineruProfile"
if (`$MineruProfile -in @("wsl", "rtx5090-wsl")) {
    `$MineruStartScript = Join-Path `$ProjectRoot "scripts\mineru\start_mineru_wsl.ps1"
} else {
    `$MineruStartScript = Join-Path `$ProjectRoot "scripts\mineru\start_mineru_`$MineruProfile.ps1"
}

`$FrontendCmd = "npm run start -p 3001"
`$BackendCmd = "conda activate $($cfg.MineruEnv); python `$BackendEntry"
`$Neo4jCmd     = "neo4j.bat console"

# MySQL (if bundled)
`$MySqlBin = "$($cfg.MySqlBin)"
`$MySqlDataDir = "$($cfg.MySqlDataDir)"

Write-Host "Starting all services..." -ForegroundColor Cyan

# Redis
`$RedisStartScript = "$redisStart"
if (Test-Path `$RedisStartScript) {
    Start-Process powershell -ArgumentList "-NoExit", "-Command", "& '`$RedisStartScript'"
    Write-Host "Redis started." -ForegroundColor Green
} else {
    Write-Host "WARN: Redis not found: `$RedisStartScript" -ForegroundColor Yellow
}

# MySQL (portable)
if (`$MySqlBin -and (Test-Path `$MySqlBin)) {
    `$mysqld = Join-Path `$MySqlBin "mysqld.exe"
    if (Test-Path `$mysqld) {
        Start-Process powershell -ArgumentList "-NoExit", "-Command", "cd '`$MySqlBin\..'; .\bin\mysqld.exe --console"
        Write-Host "MySQL started." -ForegroundColor Green
    }
}

# MinerU
if (Test-Path `$MineruStartScript) {
    Start-Process powershell -ArgumentList "-NoExit", "-Command", "& '`$MineruStartScript'"
    Write-Host "MinerU API started." -ForegroundColor Green
}

# Neo4j
if (Test-Path `$Neo4jPath) {
    Start-Process powershell -ArgumentList "-NoExit", "-Command", "cd '`$Neo4jPath'; .\`$Neo4jCmd"
    Write-Host "Neo4j started." -ForegroundColor Green
}

# MinIO (UAC)
if (Test-Path `$MinioExePath) {
    Start-Process -Verb RunAs -WindowStyle Normal -FilePath "powershell" `
        -ArgumentList "-NoExit", "-Command", "& '`$MinioExePath' server '`$MinioDataDir' --console-address :`$MinioConsolePort"
    Write-Host "MinIO starting (UAC may prompt)..." -ForegroundColor Green
}

# Backend
Start-Process powershell -ArgumentList "-NoExit", "-Command", "cd '`$BackendPath'; `$BackendCmd"

# Frontend (production build)
Start-Process powershell -ArgumentList "-NoExit", "-Command", "cd '`$FrontendPath'; `$FrontendCmd"

Write-Host ""
Write-Host "All services launched. Open http://127.0.0.1:3001" -ForegroundColor Green
Write-Host "Run healthcheck: scripts\deploy\healthcheck.ps1 -ProjectRoot `$ProjectRoot" -ForegroundColor Cyan
"@

Write-Utf8NoBom $OutputPath $content
Write-Host "Generated: $OutputPath" -ForegroundColor Green
