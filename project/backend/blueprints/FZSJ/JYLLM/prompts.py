import os

PROMPT_TEMPLATES = {}


def register_prompt(name: str, template: str):
    """注册提示词模板"""
    PROMPT_TEMPLATES[name] = template


def get_prompt(name: str, **kwargs) -> str:
    """获取提示词模板并填充变量"""
    template = PROMPT_TEMPLATES.get(name)
    if not template:
        raise ValueError(f"提示词模板 '{name}' 未注册")
    return template.format(**kwargs) if kwargs else template


def get_all_prompt_names():
    """获取所有已注册的提示词名称"""
    return list(PROMPT_TEMPLATES.keys())


_SCHEME_GLOBAL_REQUIREMENTS_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "scheme_global_requirements.txt",
)


def read_scheme_global_requirements() -> str:
    """可编辑文件：对全方案（第1章 + 各方法 LLM 正文）的统一前置要求；文件为空则不拼接。"""
    try:
        with open(_SCHEME_GLOBAL_REQUIREMENTS_PATH, "r", encoding="utf-8") as f:
            return f.read().strip()
    except OSError:
        return ""


def prepend_scheme_global_requirements(user_block: str) -> str:
    """将 `scheme_global_requirements.txt` 内容置于用户提示最前（整体化要求）。"""
    g = read_scheme_global_requirements()
    if not g:
        return user_block
    return (
        "## 【方案整体要求】\n\n"
        "（以下段落来自 `backend/blueprints/FZSJ/JYLLM/scheme_global_requirements.txt`，可直接编辑该 UTF-8 文本文件。）\n\n"
        f"{g}\n\n---\n\n"
        f"{user_block}"
    )


